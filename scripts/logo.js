/**
 * Draws the Things logo from the title face, Domaine Display Narrow Medium.
 *
 * - Wordmark: "Things", kerned as the font sets it. The dot of the i is the one
 *   bright thing: SS's accent, blue by day and ember by night, the option you
 *   end up choosing.
 * - Mark: "T.", its full stop in the same accent; Medium holds up at 16px.
 *
 * The glyphs are outlined, so no font ships with the logo. The faces are read
 * like scripts/fonts.js reads them: SS_PRIVATE_FONTS=<stevehoang.com>/public/
 * assets/fonts, else fetched from stevehoang.com. Colours are SS's roles.
 *
 * Writes src/lib/logo.ts (paths for the app), static/logo.svg and
 * static/favicon.svg. Run with `npm run logo`.
 */
import { readFile, writeFile } from 'node:fs/promises';
import opentype from 'opentype.js';
import { roles } from 'ss';
import wawoff2 from 'wawoff2';

const FACE = 'domaine-display-narrow/svn-domaine-display-narrow-medium.woff2';

async function load(file) {
	const local = process.env.SS_PRIVATE_FONTS;
	let woff2;
	if (local) woff2 = await readFile(`${local}/${file}`);
	else {
		const res = await fetch(`https://stevehoang.com/assets/fonts/${file}`, { signal: AbortSignal.timeout(8000) });
		if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
		woff2 = Buffer.from(await res.arrayBuffer());
	}
	const ttf = await wawoff2.decompress(woff2);
	return opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));
}

const join = (paths) => {
	const all = new opentype.Path();
	all.commands = paths.flatMap((p) => p.commands);
	return all;
};

/** Contours of a glyph path, each ending at its Z. */
function contours(path) {
	const out = [];
	let current = [];
	for (const command of path.commands) {
		current.push(command);
		if (command.type === 'Z') {
			out.push(join([{ commands: current }]));
			current = [];
		}
	}
	return out;
}

const box = (path, pad) => {
	const b = path.getBoundingBox();
	return { x: b.x1 - pad, y: b.y1 - pad, w: b.x2 - b.x1 + pad * 2, h: b.y2 - b.y1 + pad * 2 };
};

const view = ({ x, y, w, h }) => [x, y, w, h].map((n) => Math.round(n)).join(' ');

const medium = await load(FACE);

// Wordmark: every glyph in ink, except the i's tittle (its topmost contour).
const text = 'Things';
const glyphs = medium.getPaths(text, 0, 0, 1000, { kerning: true });
const ink = [];
const dot = [];
[...text].forEach((char, i) => {
	if (char !== 'i') return ink.push(glyphs[i]);
	const [tittle, ...stem] = contours(glyphs[i]).sort((a, b) => a.getBoundingBox().y1 - b.getBoundingBox().y1);
	dot.push(tittle);
	ink.push(...stem);
});
const wordmark = {
	viewBox: view(box(join(glyphs), 20)),
	ink: join(ink).toPathData(1),
	dot: join(dot).toPathData(1)
};

// Mark: "T." centred in a square with 14% air on the longer side.
const [t, stop] = medium.getPaths('T.', 0, 0, 1000, { kerning: true });
const b = box(join([t, stop]), 0);
const side = Math.max(b.w, b.h) * 1.28;
const mark = {
	viewBox: view({ x: b.x - (side - b.w) / 2, y: b.y - (side - b.h) / 2, w: side, h: side }),
	ink: t.toPathData(1),
	dot: stop.toPathData(1)
};

const svg = ({ viewBox, ink, dot }, label) =>
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="${label}">` +
	`<style>.ink{fill:${roles.tx.light}}.dot{fill:${roles.accent.light}}` +
	`@media (prefers-color-scheme:dark){.ink{fill:${roles.tx.dark}}.dot{fill:${roles.accent.dark}}}</style>` +
	`<path class="ink" d="${ink}"/><path class="dot" d="${dot}"/></svg>\n`;

await writeFile(new URL('../static/logo.svg', import.meta.url), svg(wordmark, 'Things'));
await writeFile(new URL('../static/favicon.svg', import.meta.url), svg(mark, 'Things'));
await writeFile(
	new URL('../src/lib/logo.ts', import.meta.url),
	`// Generated by scripts/logo.js from Domaine Display Narrow Medium. Do not edit.\n` +
		`export const wordmark = ${JSON.stringify(wordmark, null, '\t')};\n\n` +
		`export const mark = ${JSON.stringify(mark, null, '\t')};\n`
);
console.log(`logo: wordmark ${wordmark.viewBox}, mark ${mark.viewBox}`);
